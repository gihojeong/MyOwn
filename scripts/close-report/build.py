# ---------- 헬퍼 (자체완결 행) ----------
def pc(t):
    """포맷을 거치지 않은 리터럴 '%%'가 본문에 새는 것을 막는 안전망.
       % 포맷을 거친 문자열은 이미 '%'가 되어 있으므로 이중 치환 위험이 없다."""
    return t.replace("%%", "%")
def sec(t, sub=""):
    t = pc(t); sub = pc(sub)
    w('<tr><td style="padding:16px 24px 0"><font style="font-size:15px" color="%s"><b>%s</b></font>%s</td></tr>' % (
        BAND, t, ('<br><font style="font-size:11px" color="#6b7566">%s</font>' % sub) if sub else ""))
def para(t):
    t = pc(t)
    w('<tr><td style="padding:9px 24px 0"><font style="font-size:12px">%s</font></td></tr>' % t)
def box(t, bg=HL, bc=C_UP):
    t = pc(t)
    w('<tr><td style="padding:10px 24px 0"><table width="100%%" cellpadding="10" cellspacing="0" bgcolor="%s" '
      'style="border-left:3px solid %s"><tr><td><font style="font-size:12px">%s</font></td></tr></table></td></tr>' % (bg,bc,t))
def mono(t):
    t = pc(t)
    w('<tr><td style="padding:10px 24px 0"><table width="100%%" cellpadding="11" cellspacing="0" bgcolor="%s"><tr><td>'
      '<font color="#c8e6d0" style="font-family:Consolas,monospace;font-size:11px">%s</font>'
      '</td></tr></table></td></tr>' % (BAND, t))
def tbl(head, body, widths=None):
    head = [pc(x) for x in head]
